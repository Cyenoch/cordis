func writeAuthorFile(t *testing.T, dir, name, data string) {
	t.Helper()
	full := filepath.Join(dir, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(full), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(data), 0600); err != nil {
		t.Fatal(err)
	}
}

const minimalAuthorJSON = `{"id":"demo","version":"1.2.3","publisher":"example","runtime":{"kind":"native","artifacts":[{"os":"darwin","arch":"arm64","path":"plugin"}]},"contract":{"definitions":[{"id":"main"}]}}`

func TestLoadAuthorFormatsAndDefaults(t *testing.T) {
	t.Parallel()
	formats := []struct{ name, data string }{
		{"plugin.json", minimalAuthorJSON},
		{"plugin.yaml", "id: demo\nversion: 1.2.3\npublisher: example\nruntime: {kind: native, artifacts: [{os: darwin, arch: arm64, path: plugin}]}\ncontract:\n  definitions:\n    - id: main\n"},
		{"plugin.yml", "id: demo\nversion: 1.2.3\npublisher: example\nruntime: {kind: native, artifacts: [{os: darwin, arch: arm64, path: plugin}]}\ncontract: {definitions: [{id: main}]}\n"},
		{"plugin.toml", "id='demo'\nversion='1.2.3'\npublisher='example'\n[runtime]\nkind='native'\n[[runtime.artifacts]]\nos='darwin'\narch='arm64'\npath='plugin'\n[[contract.definitions]]\nid='main'\n"},
	}
	fingerprint := ""
	for _, tt := range formats {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			writeAuthorFile(t, dir, tt.name, tt.data)
			a, err := LoadAuthor(filepath.Join(dir, tt.name))
			if err != nil {
				t.Fatal(err)
			}
			m := a.Manifest
			if m.DefaultDefinition != "main" || m.Protocol.Major != 1 {
				t.Fatalf("defaults not applied: %+v", m)
			}
			if m.Dependencies == nil || m.OptionalDependencies == nil {
				t.Fatal("omitted lists are not explicit empty lists")
			}
			if len(m.Definitions[0].ConfigSchema) == 0 || m.Definitions[0].Requires == nil || m.Definitions[0].Provides == nil {
				t.Fatal("definition does not have explicit metadata")
			}
			if fingerprint != "" && fingerprint != a.Fingerprint {
				t.Fatalf("format changed fingerprint: %s != %s", a.Fingerprint, fingerprint)
			}
			fingerprint = a.Fingerprint
			var generated bytes.Buffer
			if err := a.Generate(&generated, "main"); err != nil {
				t.Fatal(err)
			}
			if !bytes.Contains(generated.Bytes(), []byte("NewMainDefinition")) {
				t.Fatal("missing typed definition constructor")
			}
			got, err := os.ReadFile(filepath.Join(dir, tt.name))
			if err != nil || string(got) != tt.data {
				t.Fatalf("loader changed source: %q, %v", got, err)
			}
		})
	}
}

func TestLoadAuthorRejectsAmbiguityAndOldMachineFields(t *testing.T) {
	t.Parallel()
	t.Run("explicit source still rejects ambiguity", func(t *testing.T) {
		dir := t.TempDir()
		writeAuthorFile(t, dir, "plugin.json", minimalAuthorJSON)
		writeAuthorFile(t, dir, "plugin.toml", "")
		if _, err := LoadAuthor(filepath.Join(dir, "plugin.json")); err == nil || !strings.Contains(err.Error(), "expected one") {
			t.Fatalf("ambiguous source: %v", err)
		}
	})
	for _, tt := range []struct{ name, data string }{
		{"machine missing definition schema", `{"schema":"cordis-go.package/v1","id":"demo","version":"1.0.0","publisher":"example","protocol":{"major":1},"definitions":[{"id":"main"}],"defaultDefinition":"main","runtime":{"kind":"native","artifacts":[{"os":"darwin","arch":"arm64","path":"plugin"}]}}`},
		{"old package configSchema", strings.Replace(minimalAuthorJSON, `"contract":`, `"configSchema":{"type":"object"},"contract":`, 1)},
		{"unknown machine schema", strings.Replace(minimalAuthorJSON, `"id":"demo"`, `"schema":"old","id":"demo"`, 1)},
		{"multiple definitions need default", strings.Replace(minimalAuthorJSON, `{"id":"main"}`, `{"id":"main"},{"id":"other"}`, 1)},
		{"mixed contract sources", strings.Replace(minimalAuthorJSON, `"contract":`, `"contracts":["other.json"],"contract":`, 1)},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			writeAuthorFile(t, dir, "plugin.json", tt.data)
			if _, err := LoadAuthor(dir); err == nil {
				t.Fatal("accepted invalid declaration")
			}
		})
	}
	// Current machine metadata is accepted as-is, never enriched with author defaults.
	dir := t.TempDir()
	raw, err := json.Marshal(manifestFixture("demo", "1.0.0"))
	if err != nil {
		t.Fatal(err)
	}
	writeAuthorFile(t, dir, ManifestFile, string(raw))
	a, err := LoadAuthor(dir)
	if err != nil || len(a.Contracts) != 0 {
		t.Fatalf("current machine manifest: %+v, %v", a, err)
	}
}

func TestLoadAuthorContractReferences(t *testing.T) {
	t.Parallel()
	for _, tt := range []struct{ name, ref, content string }{
		{"parent escape", "../outside.json", "{}"},
		{"absolute path", "/tmp/contract.json", "{}"},
		{"network", "https://example.com/contract.json", "{}"},
		{"cycle", "contracts.json", `{"contracts":["contracts.json"]}`},
		{"cycle to source", "contracts.json", `{"contracts":["plugin.json"]}`},
		{"schema reference cycle", "contracts.json", `{"types":{"Loop":{"$ref":"#/types/Loop"}},"definitions":[{"id":"main","config":{"$ref":"#/types/Loop"}}]}`},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			data := strings.Replace(minimalAuthorJSON, `"contract":{"definitions":[{"id":"main"}]}`, `"contracts":[`+strconv.Quote(tt.ref)+`]`, 1)
			writeAuthorFile(t, dir, "plugin.json", data)
			if tt.ref == "contracts.json" {
				writeAuthorFile(t, dir, tt.ref, tt.content)
			}
			if _, err := LoadAuthor(dir); err == nil {
				t.Fatal("accepted unsafe or cyclic reference")
			}
		})
	}
	dir := t.TempDir()
	writeAuthorFile(t, dir, "plugin.json", strings.Replace(minimalAuthorJSON, `"contract":{"definitions":[{"id":"main"}]}`, `"contracts":["contracts/list.yaml"]`, 1))
	writeAuthorFile(t, dir, "contracts/list.yaml", "contracts: ['contracts/main.toml']")
	writeAuthorFile(t, dir, "contracts/main.toml", "[[definitions]]\nid='main'\n")
	if _, err := LoadAuthor(dir); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(dir, "contracts/main.toml")); err != nil {
		t.Fatal(err)
	}
	outside := filepath.Join(t.TempDir(), "main.toml")
	writeAuthorFile(t, filepath.Dir(outside), "main.toml", "[[definitions]]\nid='main'\n")
	if err := os.Symlink(outside, filepath.Join(dir, "contracts/main.toml")); err != nil {
		t.Skipf("symlink unavailable: %v", err)
	}
	if _, err := LoadAuthor(dir); err == nil {
		t.Fatal("accepted linked contract")
	}
}

func TestLoadAuthorServiceAndPackageVersion(t *testing.T) {
	t.Parallel()
	for _, version := range []string{`1`, `"1.2"`, `1.2`, `"1.2.3"`} {
		t.Run(version, func(t *testing.T) {
			dir := t.TempDir()
			declaration := `{"definitions":[{"id":"main","provides":["echo"]}],"services":[{"name":"echo","version":` + version + `,"methods":[{"name":"send","request":{"type":"object"},"response":{"type":"object"}}]}]}`
			data := strings.Replace(minimalAuthorJSON, `{"definitions":[{"id":"main"}]}`, declaration, 1)
			data = strings.Replace(data, `"version":"1.2.3"`, `"version":"2.0.0"`, 1)
			writeAuthorFile(t, dir, "plugin.json", data)
			a, err := LoadAuthor(dir)
			valid := version == `1` || version == `"1.2"`
			if (err == nil) != valid {
				t.Fatalf("version %s: %v", version, err)
			}
			if valid && (a.Manifest.Version != "2.0.0") {
				t.Fatal("release version changed")
			}
		})
	}
}

func TestLoadAuthorConsumerRequiresExplicitClosedRange(t *testing.T) {
	t.Parallel()
	for _, tt := range []struct {
		name, consumer string
		valid          bool
	}{
		{"explicit zero range", `{"name":"client","service":"echo","minMinor":0,"maxMinor":0}`, true},
		{"missing range", `{"name":"client","service":"echo"}`, false},
		{"missing minimum", `{"name":"client","service":"echo","maxMinor":0}`, false},
		{"missing maximum", `{"name":"client","service":"echo","minMinor":0}`, false},
		{"inverted range", `{"name":"client","service":"echo","minMinor":2,"maxMinor":1}`, false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			declaration := `{"definitions":[{"id":"main","requires":[` + tt.consumer + `]}],"services":[{"name":"echo","version":1,"methods":[{"name":"send","request":{"type":"object"},"response":{"type":"object"}}]}]}`
			data := strings.Replace(minimalAuthorJSON, `{"definitions":[{"id":"main"}]}`, declaration, 1)
			writeAuthorFile(t, dir, "plugin.json", data)
			a, err := LoadAuthor(dir)
			if (err == nil) != tt.valid {
				t.Fatalf("consumer range: %v", err)
			}
			if tt.valid {
				c := a.Manifest.Definitions[0].Requires[0]
				if c.Requirement.MinMinor != 0 || c.Requirement.MaxMinor != 0 || !validHash(c.Contract) {
					t.Fatalf("incorrect consumer projection: %+v", c)
				}
			}
		})
	}
}

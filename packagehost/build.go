const BuildSchema = "cordis-go.build/v1"
const BuildDescriptorFile = "build.json"
const sdkModule = "github.com/Cyenoch/cordis"

type BuildOptions struct {
	GoPackage        string
	Output           string
	GOOS             string
	GOARCH           string
	GeneratedPackage string
	GeneratedOutput  string
}

// SDKBuild records the dependency actually selected by Go, including replaces.
type SDKBuild struct {
	Module       string            `json:"module"`
	Version      string            `json:"version"`
	Sum          string            `json:"sum,omitempty"`
	Replace      *debug.Module     `json:"replace,omitempty"`
	Protocol     contract.Protocol `json:"protocol"`
	Features     []string          `json:"features"`
	Capabilities string            `json:"capabilities"`
}

type BuildTarget struct {
	OS     string `json:"os"`
	Arch   string `json:"arch"`
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

// BuildDescriptor is tool output, not another author-maintained Manifest.
// External build pipelines must explicitly supply the same evidence.
type BuildDescriptor struct {
	Schema                 string        `json:"schema"`
	DeclarationFingerprint string        `json:"declarationFingerprint"`
	GeneratedFingerprint   string        `json:"generatedFingerprint"`
	GeneratedPackage       string        `json:"generatedPackage"`
	GeneratedOutput        string        `json:"generatedOutput"`
	SDK                    SDKBuild      `json:"sdk"`
	Targets                []BuildTarget `json:"targets"`
}

// PrepareBuild generates atomically and resolves capabilities from the actual
// Go dependency. GoPackage, GOOS and GOARCH are required, never host defaults.
// Output defaults to the declared target; generated defaults are main/cordis_gen.go.
// It does not write build.json or claim a target has been built.
func PrepareBuild(ctx context.Context, sourceDir string, options BuildOptions) (*Author, BuildDescriptor, error) {
	flags, err := runGo(ctx, sourceDir, options, "env", "GOFLAGS")
	if err != nil {
		return nil, BuildDescriptor{}, err
	}
	for _, flag := range strings.Fields(string(flags)) {
		flag = strings.Trim(flag, "\"'")
		if flag == "-overlay" || strings.HasPrefix(flag, "-overlay=") {
			return nil, BuildDescriptor{}, fmt.Errorf("automatic SDK proof does not support Go -overlay; external builds require an explicit descriptor")
		}
	}
	a, err := LoadAuthor(sourceDir)
	if err != nil {
		return nil, BuildDescriptor{}, err
	}
	options, err = normalizeBuildOptions(a, options)
	if err != nil {
		return nil, BuildDescriptor{}, err
	}
	var generated bytes.Buffer
	if err := a.Generate(&generated, options.GeneratedPackage); err != nil {
		return nil, BuildDescriptor{}, err
	}
	if err := ctx.Err(); err != nil {
		return nil, BuildDescriptor{}, err
	}
	if err := atomicBuildFile(sourceDir, options.GeneratedOutput, generated.Bytes()); err != nil {
		return nil, BuildDescriptor{}, err
	}
	sdk, err := resolveSDK(ctx, sourceDir, options)
	if err != nil {
		return nil, BuildDescriptor{}, err
	}
	d := BuildDescriptor{
		Schema: BuildSchema, DeclarationFingerprint: a.Fingerprint,
		GeneratedFingerprint: hashBytes(generated.Bytes()), GeneratedPackage: options.GeneratedPackage,
		GeneratedOutput: options.GeneratedOutput, SDK: sdk, Targets: []BuildTarget{},
	}
	a.Manifest.Protocol = sdk.Protocol
	return a, d, nil
}

// Build generates, builds the exact requested Go target without executing it,
// hashes the resulting artifact and atomically writes build.json.
func Build(ctx context.Context, sourceDir string, options BuildOptions) (BuildDescriptor, error) {
	a, d, err := PrepareBuild(ctx, sourceDir, options)
	if err != nil {
		return d, err
	}
	options, err = normalizeBuildOptions(a, options)
	if err != nil {
		return d, err
	}
	prior, priorErr := readBuildDescriptor(sourceDir)
	if priorErr != nil && !errors.Is(priorErr, os.ErrNotExist) {
		return d, priorErr
	}
	output := filepath.Join(sourceDir, filepath.FromSlash(options.Output))
	root, err := os.OpenRoot(sourceDir)
	if err != nil {
		return d, err
	}
	defer root.Close()
	if err := root.MkdirAll(filepath.Dir(filepath.FromSlash(options.Output)), 0700); err != nil {
		return d, err
	}
	if err := checkSourceParents(root, options.Output); err != nil {
		return d, err
	}
	f, err := os.CreateTemp(filepath.Dir(output), ".cordis-build-*")
	if err != nil {
		return d, err
	}
	name := f.Name()
	defer os.Remove(name)
	if err := f.Close(); err != nil {
		return d, err
	}
	absolute, err := filepath.Abs(name)
	if err != nil {
		return d, err
	}
	if _, err := runGo(ctx, sourceDir, options, "build", "-o", absolute, options.GoPackage); err != nil {
		return d, err
	}
	if err := checkBinarySDK(name, options.GOOS, options.GOARCH, d.SDK); err != nil {
		return d, err
	}
	hash, err := hashBuildFile(ctx, nil, name)
	if err != nil {
		return d, err
	}
	if err := ctx.Err(); err != nil {
		return d, err
	}
	if err := replaceFile(name, output); err != nil {
		return d, err
	}
	target := BuildTarget{OS: options.GOOS, Arch: options.GOARCH, Path: options.Output, SHA256: hash}
	if priorErr == nil && sameBuildInputs(prior, d) {
		for _, old := range prior.Targets {
			if old.OS != target.OS || old.Arch != target.Arch {
				d.Targets = append(d.Targets, old)
			}
		}
	}
	d.Targets = append(d.Targets, target)
	if err := WriteBuildDescriptor(sourceDir, d); err != nil {
		return d, err
	}
	return d, nil
}

func normalizeBuildOptions(a *Author, o BuildOptions) (BuildOptions, error) {
	if len(a.Contracts) == 0 {
		return o, fmt.Errorf("build requires an author source, not a machine Manifest")
	}
	if o.GoPackage == "" || strings.HasPrefix(o.GoPackage, "-") || strings.Contains(o.GoPackage, "...") {
		return o, fmt.Errorf("build requires one explicit Go package")
	}
	if !validName(o.GOOS) || !validName(o.GOARCH) {
		return o, fmt.Errorf("build requires explicit GOOS and GOARCH")
	}
	artifact, err := Artifact(a.Manifest, o.GOOS, o.GOARCH)
	if err != nil {
		return o, err
	}
	if o.Output == "" {
		o.Output = artifact
	}
	if o.Output != artifact {
		return o, fmt.Errorf("build output %q does not match declared artifact %q", o.Output, artifact)
	}
	if o.GeneratedPackage == "" {
		o.GeneratedPackage = "main"
	}
	if o.GeneratedOutput == "" {
		o.GeneratedOutput = "cordis_gen.go"
	}
	if err := validateBuildPath(o.Output); err != nil {
		return o, err
	}
	if err := validateBuildPath(o.GeneratedOutput); err != nil {
		return o, err
	}
	if o.GeneratedOutput == o.Output || !strings.HasSuffix(o.GeneratedOutput, ".go") {
		return o, fmt.Errorf("generated output must be a separate .go file")
	}
	return o, nil
}

func validateBuildPath(name string) error {
	if err := validatePath(name); err != nil {
		return err
	}
	for _, reserved := range append(append([]string{}, authorCandidates...), IntegrityFile, SignatureFile, BuildDescriptorFile) {
		if name == reserved {
			return fmt.Errorf("build output uses reserved metadata path %q", name)
		}
	}
	return nil
}

func runGo(ctx context.Context, dir string, o BuildOptions, args ...string) (output []byte, result error) {
	temporary, err := os.MkdirTemp(os.Getenv("GOTMPDIR"), ".cordis-go-")
	if err != nil {
		return nil, fmt.Errorf("create Go build workspace: %w", err)
	}
	defer func() { result = errors.Join(result, os.RemoveAll(temporary)) }()
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = []string{}
	for _, entry := range os.Environ() {
		if !strings.HasPrefix(entry, "GOOS=") && !strings.HasPrefix(entry, "GOARCH=") && !strings.HasPrefix(entry, "GOTMPDIR=") {
			cmd.Env = append(cmd.Env, entry)
		}
	}
	cmd.Env = append(cmd.Env, "GOOS="+o.GOOS, "GOARCH="+o.GOARCH, "GOTMPDIR="+temporary)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err = processtree.Run(ctx, cmd)
	if err != nil {
		return nil, fmt.Errorf("go %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return stdout.Bytes(), nil
}

func resolveSDK(ctx context.Context, dir string, options BuildOptions) (SDKBuild, error) {
	raw, err := runGo(ctx, dir, options, "list", "-deps", "-json", options.GoPackage)
	if err != nil {
		return SDKBuild{}, err
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	generated, err := filepath.Abs(filepath.Join(dir, filepath.FromSlash(options.GeneratedOutput)))
	if err != nil {
		return SDKBuild{}, err
	}
	generatedInfo, err := os.Stat(generated)
	if err != nil {
		return SDKBuild{}, err
	}
	var sdk SDKBuild
	compiledGenerated := false
	mainPackages := 0
	for decoder.More() {
		var p struct {
			ImportPath string
			Dir        string
			Name       string
			GoFiles    []string
			DepOnly    bool
			Module     *debug.Module
		}
		if err := decoder.Decode(&p); err != nil {
			return SDKBuild{}, fmt.Errorf("read Go dependency information: %w", err)
		}
		if !p.DepOnly {
			if p.Name != "main" {
				return SDKBuild{}, fmt.Errorf("build target %q is not a main package", p.ImportPath)
			}
			mainPackages++
		}
		for _, name := range p.GoFiles {
			info, err := os.Stat(filepath.Join(p.Dir, name))
			if err != nil {
				return SDKBuild{}, err
			}
			if os.SameFile(info, generatedInfo) {
				compiledGenerated = true
			}
		}
		if p.ImportPath != sdkModule+"/sdk" {
			continue
		}
		if p.Module == nil || p.Module.Path != sdkModule {
			return SDKBuild{}, fmt.Errorf("SDK dependency has no module identity")
		}
		data, err := readMetadata(p.Dir, "capabilities.json")
		if err != nil {
			return SDKBuild{}, fmt.Errorf("actual SDK %s capabilities: %w; external builds require an explicit descriptor", p.Dir, err)
		}
		var capabilities struct {
			Schema   string            `json:"schema"`
			Protocol contract.Protocol `json:"protocol"`
			Features []string          `json:"features"`
		}
		if err := contract.Decode(data, &capabilities); err != nil {
			return SDKBuild{}, fmt.Errorf("actual SDK capabilities: %w", err)
		}
		if capabilities.Schema != "cordis-go.sdk/v1" {
			return SDKBuild{}, fmt.Errorf("unsupported actual SDK capability schema %q", capabilities.Schema)
		}
		version := p.Module.Version
		if version == "" {
			version = "(devel)"
		}
		if p.Module.Replace != nil && p.Module.Replace.Version == "" {
			p.Module.Replace.Version = "(devel)"
		}
		sdk = SDKBuild{
			Module: p.Module.Path, Version: version, Sum: p.Module.Sum, Replace: p.Module.Replace,
			Protocol: capabilities.Protocol, Features: capabilities.Features, Capabilities: hashBytes(data),
		}
	}
	if sdk.Module == "" {
		return SDKBuild{}, fmt.Errorf("Go package %q does not depend on the Cordis SDK", options.GoPackage)
	}
	if mainPackages != 1 || !compiledGenerated {
		return SDKBuild{}, fmt.Errorf("build requires one main package that compiles generated contract %q", options.GeneratedOutput)
	}
	return sdk, nil
}

// WriteBuildDescriptor atomically records explicit external-build evidence.
// Pack still verifies the declaration, generated bytes and every artifact hash.
func WriteBuildDescriptor(dir string, descriptor BuildDescriptor) error {
	if err := validateBuildDescriptor(descriptor); err != nil {
		return err
	}
	slices.SortFunc(descriptor.Targets, func(a, b BuildTarget) int {
		return strings.Compare(a.OS+"/"+a.Arch, b.OS+"/"+b.Arch)
	})
	raw, err := json.MarshalIndent(descriptor, "", "  ")
	if err != nil {
		return err
	}
	return atomicBuildFile(dir, BuildDescriptorFile, append(raw, '\n'))
}

func readBuildDescriptor(dir string) (BuildDescriptor, error) {
	var d BuildDescriptor
	raw, err := readMetadata(dir, BuildDescriptorFile)
	if err != nil {
		return d, err
	}
	if err := contract.Decode(raw, &d); err != nil {
		return d, fmt.Errorf("%s: %w", BuildDescriptorFile, err)
	}
	return d, validateBuildDescriptor(d)
}

func validateBuildDescriptor(d BuildDescriptor) error {
	if d.Schema != BuildSchema || !validHash(d.DeclarationFingerprint) || !validHash(d.GeneratedFingerprint) {
		return fmt.Errorf("%s: invalid schema or declaration/generated fingerprint", BuildDescriptorFile)
	}
	if err := validateBuildPath(d.GeneratedOutput); err != nil {
		return err
	}
	if d.SDK.Module != sdkModule || d.SDK.Version == "" || !validHash(d.SDK.Capabilities) {
		return fmt.Errorf("%s: missing actual SDK module/version/capabilities", BuildDescriptorFile)
	}
	if d.GeneratedPackage == "" || !strings.HasSuffix(d.GeneratedOutput, ".go") {
		return fmt.Errorf("%s: missing generated Go package or .go output", BuildDescriptorFile)
	}
	p := d.SDK.Protocol
	if p.Major != 1 || p.MinMinor != 0 || p.MinMinor > p.MaxMinor {
		return fmt.Errorf("%s: unsupported SDK protocol", BuildDescriptorFile)
	}
	seen := map[string]bool{}
	for _, feature := range d.SDK.Features {
		if !validName(feature) || seen[feature] {
			return fmt.Errorf("%s: invalid SDK feature %q", BuildDescriptorFile, feature)
		}
		seen[feature] = true
	}
	for _, required := range p.RequiredFeatures {
		if !seen[required] {
			return fmt.Errorf("%s: SDK lacks required feature %q", BuildDescriptorFile, required)
		}
	}
	seen = map[string]bool{}
	if len(d.Targets) == 0 {
		return fmt.Errorf("%s: no built targets", BuildDescriptorFile)
	}
	for _, t := range d.Targets {
		key := t.OS + "/" + t.Arch
		if !validName(t.OS) || !validName(t.Arch) || seen[key] || !validHash(t.SHA256) {
			return fmt.Errorf("%s: invalid or duplicate build target %q", BuildDescriptorFile, key)
		}
		if err := validateBuildPath(t.Path); err != nil {
			return err
		}
		seen[key] = true
	}
	return nil
}

func validHash(value string) bool {
	hash, err := hex.DecodeString(value)
	return err == nil && len(hash) == sha256.Size && strings.ToLower(value) == value
}

func sameBuildInputs(a, b BuildDescriptor) bool {
	a.Targets, b.Targets = nil, nil
	return reflect.DeepEqual(a, b)
}

func hashBuildFile(ctx context.Context, root *os.Root, name string) (string, error) {
	if root != nil {
		if err := checkSourceParents(root, name); err != nil {
			return "", err
		}
	}
	f, err := openRegular(root, name)
	if err != nil {
		return "", err
	}
	info, err := f.Stat()
	if err == nil {
		err = checkLinks(f, info)
	}
	if err != nil {
		return "", errors.Join(err, f.Close())
	}
	h := sha256.New()
	n, err := io.Copy(h, io.LimitReader(&contextReader{ctx: ctx, reader: f}, DefaultLimits().FileBytes+1))
	err = errors.Join(err, f.Close())
	if err != nil {
		return "", err
	}
	if n > DefaultLimits().FileBytes {
		return "", fmt.Errorf("%s exceeds build file quota", name)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func atomicBuildFile(dir, name string, data []byte) (err error) {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	parent := filepath.Dir(filepath.FromSlash(name))
	if err := root.MkdirAll(parent, 0700); err != nil {
		return err
	}
	if err := checkSourceParents(root, name); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Join(dir, parent), ".cordis-generate-*")
	if err != nil {
		return err
	}
	temp := f.Name()
	defer os.Remove(temp)
	_, err = f.Write(data)
	if err == nil {
		err = f.Sync()
	}
	err = errors.Join(err, f.Close())
	if err != nil {
		return err
	}
	if err := replaceFile(temp, filepath.Join(dir, filepath.FromSlash(name))); err != nil {
		return err
	}
	return syncDir(filepath.Join(dir, parent))
}

func checkBinarySDK(file, goos, goarch string, sdk SDKBuild) error {
	info, err := buildinfo.ReadFile(file)
	if err != nil {
		return fmt.Errorf("read artifact SDK build info: %w", err)
	}
	settings := map[string]string{}
	for _, setting := range info.Settings {
		settings[setting.Key] = setting.Value
	}
	if settings["GOOS"] != goos || settings["GOARCH"] != goarch {
		return fmt.Errorf("artifact build target does not match %s/%s", goos, goarch)
	}
	modules := append([]*debug.Module{&info.Main}, info.Deps...)
	for _, m := range modules {
		if m.Path == sdk.Module {
			version := m.Version
			if version == "" {
				version = "(devel)"
			}
			if version != sdk.Version || m.Sum != sdk.Sum || !reflect.DeepEqual(m.Replace, sdk.Replace) {
				return fmt.Errorf("artifact SDK module does not match build descriptor")
			}
			return nil
		}
	}
	return fmt.Errorf("artifact does not contain the declared SDK module")
}

// stageAuthor runs only against Pack's private, bounded snapshot. All generated
// metadata exists before generateIntegrity, so no unsigned sidecar is consulted.
func stageAuthor(ctx context.Context, dir string) error {
	a, err := LoadAuthor(dir)
	if err != nil {
		return err
	}
	if len(a.Contracts) == 0 {
		return nil
	}
	d, err := readBuildDescriptor(dir)
	if err != nil {
		return fmt.Errorf("%s: author package requires an explicit %s: %w", a.Source, BuildDescriptorFile, err)
	}
	if d.DeclarationFingerprint != a.Fingerprint {
		return fmt.Errorf("%s: declaration changed; regenerate and rebuild before packing", a.Source)
	}
	var generated bytes.Buffer
	if err := a.Generate(&generated, d.GeneratedPackage); err != nil {
		return err
	}
	if hashBytes(generated.Bytes()) != d.GeneratedFingerprint {
		return fmt.Errorf("%s: generated contract is stale; regenerate %s", a.Source, d.GeneratedOutput)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	hash, err := hashBuildFile(ctx, root, d.GeneratedOutput)
	if err != nil {
		return fmt.Errorf("generated contract %s: %w", d.GeneratedOutput, err)
	}
	if hash != d.GeneratedFingerprint {
		return fmt.Errorf("generated contract %s changed; regenerate and rebuild", d.GeneratedOutput)
	}
	expected := map[string]string{}
	for _, target := range a.Manifest.Runtime.Artifacts {
		expected[target.OS+"/"+target.Arch] = target.Path
	}
	if len(d.Targets) != len(expected) {
		return fmt.Errorf("%s: built targets do not cover the declared runtime artifacts", BuildDescriptorFile)
	}
	for _, target := range d.Targets {
		if expected[target.OS+"/"+target.Arch] != target.Path {
			return fmt.Errorf("%s: target %s/%s does not match runtime artifact", BuildDescriptorFile, target.OS, target.Arch)
		}
		hash, err := hashBuildFile(ctx, root, target.Path)
		if err != nil {
			return fmt.Errorf("build target %s: %w", target.Path, err)
		}
		if hash != target.SHA256 {
			return fmt.Errorf("build target %s hash changed; rebuild before packing", target.Path)
		}
		if err := checkBinarySDK(filepath.Join(dir, filepath.FromSlash(target.Path)), target.OS, target.Arch, d.SDK); err != nil {
			return fmt.Errorf("build target %s: %w", target.Path, err)
		}
	}
	a.Manifest.Protocol = d.SDK.Protocol
	if err := ValidateManifest(a.Manifest); err != nil {
		return err
	}
	raw, err := json.Marshal(a.Manifest)
	if err != nil {
		return err
	}
	if err := os.Remove(filepath.Join(dir, a.Source)); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, ManifestFile), raw, 0600)
}

func externalAuthorBuild(t *testing.T, dir, source string) BuildDescriptor {
	t.Helper()
	writeAuthorFile(t, dir, "plugin.toml", source)
	a, err := LoadAuthor(dir)
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := a.Generate(&generated, "main"); err != nil {
		t.Fatal(err)
	}
	writeAuthorFile(t, dir, "cordis_gen.go", generated.String())
	repo, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	writeAuthorFile(t, dir, "go.mod", "module example.net/fixture\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => "+strconv.Quote(repo)+"\n")
	writeAuthorFile(t, dir, "main.go", `package main
import("context"; "github.com/Cyenoch/cordis/contract"; "github.com/Cyenoch/cordis/sdk")
func main(){ _ = sdk.Run(context.Background(), NewMainDefinition(func(context.Context,contract.Scope,MainConfig)error{return nil})) }
`)
	d, err := Build(t.Context(), dir, BuildOptions{GoPackage: ".", GOOS: runtime.GOOS, GOARCH: runtime.GOARCH})
	if err != nil {
		t.Fatal(err)
	}
	return d

}

var minimalAuthorTOML = "id='demo'\nversion='1.2.3'\npublisher='example'\n[runtime]\nkind='native'\n[[runtime.artifacts]]\nos='" + runtime.GOOS + "'\narch='" + runtime.GOARCH + "'\npath='plugin'\n[[contract.definitions]]\nid='main'\n"

func TestPackAuthorStagesMachineManifestAndCoversAllFiles(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	externalAuthorBuild(t, dir, minimalAuthorTOML)
	writeAuthorFile(t, dir, "assets/message.txt", "signed payload")
	archive := filepath.Join(t.TempDir(), "plugin.zip")
	p, err := Pack(context.Background(), dir, archive)
	if err != nil {
		t.Fatal(err)
	}
	if p.Manifest.DefaultDefinition != "main" || p.Manifest.Version != "1.2.3" {
		t.Fatalf("wrong package metadata: %+v", p.Manifest)
	}
	source, err := os.ReadFile(filepath.Join(dir, "plugin.toml"))
	if err != nil || string(source) != minimalAuthorTOML {
		t.Fatalf("source changed: %q, %v", source, err)
	}
	if _, err := os.Stat(filepath.Join(dir, ManifestFile)); !os.IsNotExist(err) {
		t.Fatalf("machine manifest leaked into source: %v", err)
	}
	z, err := zip.OpenReader(archive)
	if err != nil {
		t.Fatal(err)
	}
	defer z.Close()
	files := map[string][]byte{}
	for _, f := range z.File {
		r, err := f.Open()
		if err != nil {
			t.Fatal(err)
		}
		data, err := io.ReadAll(r)
		if closeErr := r.Close(); err != nil || closeErr != nil {
			t.Fatalf("read zip: %v, %v", err, closeErr)
		}
		files[f.Name] = data
	}
	if _, ok := files["plugin.toml"]; ok {
		t.Fatal("archive still has author source candidate")
	}
	var manifest contract.Manifest
	if err := contract.Decode(files[ManifestFile], &manifest); err != nil {
		t.Fatal(err)
	}
	if err := ValidateManifest(manifest); err != nil {
		t.Fatal(err)
	}
	var integrity Integrity
	if err := contract.Decode(files[IntegrityFile], &integrity); err != nil {
		t.Fatal(err)
	}
	if len(integrity.Files) != len(files)-1 {
		t.Fatal("integrity misses actual archive files")
	}
	for _, entry := range integrity.Files {
		if entry.SHA256 != hashBytes(files[entry.Path]) || entry.Size != uint64(len(files[entry.Path])) {
			t.Fatalf("integrity mismatch for %s", entry.Path)
		}
	}
}

func TestPackRejectsBuildDriftWithoutReplacingArchive(t *testing.T) {
	t.Parallel()
	for _, tt := range []struct {
		name   string
		change func(*testing.T, string, BuildDescriptor)
		want   string
	}{
		{"missing descriptor", func(t *testing.T, dir string, _ BuildDescriptor) {
			if err := os.Remove(filepath.Join(dir, BuildDescriptorFile)); err != nil {
				t.Fatal(err)
			}
		}, "explicit build.json"},
		{"declaration changed", func(t *testing.T, dir string, _ BuildDescriptor) {
			writeAuthorFile(t, dir, "plugin.toml", strings.Replace(minimalAuthorTOML, "id='main'", "id='changed'", 1))
		}, "declaration changed"},
		{"generated bytes changed", func(t *testing.T, dir string, _ BuildDescriptor) {
			writeAuthorFile(t, dir, "cordis_gen.go", "package main\n")
		}, "changed"},
		{"old generator fingerprint", func(t *testing.T, dir string, d BuildDescriptor) {
			d.GeneratedFingerprint = hashBytes([]byte("old generated code"))
			if err := WriteBuildDescriptor(dir, d); err != nil {
				t.Fatal(err)
			}
		}, "stale"},
		{"generation fails", func(t *testing.T, dir string, d BuildDescriptor) {
			d.GeneratedPackage = "invalid-package"
			if err := WriteBuildDescriptor(dir, d); err != nil {
				t.Fatal(err)
			}
		}, "invalid Go package name"},
		{"artifact hash changed", func(t *testing.T, dir string, _ BuildDescriptor) {
			writeAuthorFile(t, dir, "plugin", "different artifact")
		}, "hash changed"},
		{"target changed", func(t *testing.T, dir string, d BuildDescriptor) {
			d.Targets[0].OS = "unsupported"
			if err := WriteBuildDescriptor(dir, d); err != nil {
				t.Fatal(err)
			}
		}, "does not match"},
		{"ambiguous candidate", func(t *testing.T, dir string, _ BuildDescriptor) {
			writeAuthorFile(t, dir, ManifestFile, minimalAuthorJSON)
		}, "expected one"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			d := externalAuthorBuild(t, dir, minimalAuthorTOML)
			archive := filepath.Join(t.TempDir(), "existing.zip")
			writeAuthorFile(t, filepath.Dir(archive), filepath.Base(archive), "existing archive")
			tt.change(t, dir, d)
			_, err := Pack(context.Background(), dir, archive)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("pack drift diagnostic: %v", err)
			}
			got, err := os.ReadFile(archive)
			if err != nil || string(got) != "existing archive" {
				t.Fatalf("failed pack replaced old archive: %q, %v", got, err)
			}
		})
	}
}


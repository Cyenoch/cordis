// Generate analyzes the Go package in dir and writes GoFile and ContractFile
// there. Files whose content would not change are left alone.
func Generate(ctx context.Context, dir string, target Target) (*Package, error) {
	p, err := Load(ctx, dir, target)
	if err != nil {
		return nil, err
	}
	code, err := p.Source()
	if err != nil {
		return nil, err
	}
	declared, err := p.Contract()
	if err != nil {
		return nil, err
	}
	// Both files are written out before either takes its place, so that a
	// disk that fills up or a directory that cannot be written leaves the
	// previous pair, not one new file next to one old.
	var staged []func(commit bool) error
	for _, file := range []struct {
		name string
		data []byte
	}{{ContractFile, declared}, {GoFile, code}} {
		finish, err := stage(filepath.Join(dir, file.name), file.data)
		if err != nil {
			for _, discard := range staged {
				err = errors.Join(err, discard(false))
			}
			return nil, err
		}
		staged = append(staged, finish)
	}
	var result error
	for _, commit := range staged {
		result = errors.Join(result, commit(result == nil))
	}
	if result != nil {
		return nil, result
	}
	return p, nil
}

// stage writes data next to path. The returned function puts it in place or
// discards it; a file whose content would not change is left alone.
func stage(path string, data []byte) (finish func(commit bool) error, err error) {
	if current, err := os.ReadFile(path); err == nil && bytes.Equal(current, data) {
		return func(bool) error { return nil }, nil
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".cordis-generate-*")
	if err != nil {
		return nil, err
	}
	_, err = file.Write(data)
	if err = errors.Join(err, file.Chmod(0644), file.Close()); err != nil {
		return nil, errors.Join(fmt.Errorf("write %s: %w", path, err), os.Remove(file.Name()))
	}
	return func(commit bool) error {
		if !commit {
			return os.Remove(file.Name())
		}
		if err := os.Rename(file.Name(), path); err != nil {
			return errors.Join(fmt.Errorf("write %s: %w", path, err), os.Remove(file.Name()))
		}
		return nil
	}, nil
}

// Source returns the generated Go file.
func (p *Package) Source() ([]byte, error) {
	g := &generator{source: p.source, imports: map[string]imported{}, names: map[string]bool{}}
	services := map[string]*service{}
	for _, s := range p.services {
		services[s.name] = s
	}
	plugins := map[string]*plugin{}
	for _, plugin := range p.plugins {
		plugins[plugin.id] = plugin
	}
	specs, err := p.Definition.Specs()
	if err != nil {
		return nil, err
	}
	// The canonical contract fixes the order and carries the fingerprints.
	for _, declared := range p.Definition.Services {
		if s := services[declared.Name]; s.local {
			g.service(s, declared)
		}
	}
	for index, declared := range p.Definition.Definitions {
		g.plugin(plugins[declared.ID], declared, specs[index], services)
	}
	if g.err != nil {
		return nil, g.err
	}
	var file bytes.Buffer
	fmt.Fprintf(&file, "// Code generated by cordis generate. DO NOT EDIT.\n\npackage %s\n\nimport (\n", p.source.pkg.Name())
	paths := make([]string, 0, len(g.imports))
	for path := range g.imports {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	for _, path := range paths {
		fmt.Fprintf(&file, "%s %q\n", g.imports[path].alias, path)
	}
	file.WriteString(")\n")
	file.Write(g.body.Bytes())
	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}

// imported is how the generated file refers to a package; alias is empty
// when the local name is the package's own.
type imported struct{ local, alias string }

type generator struct {
	source  *source
	body    bytes.Buffer
	imports map[string]imported
	names   map[string]bool // generated package-level names
	err     error
}

func (g *generator) line(format string, args ...any) {
	fmt.Fprintf(&g.body, format+"\n", args...)
}

// use returns the name the generated file refers to a package by.
func (g *generator) use(path, name string) string {
	if known, ok := g.imports[path]; ok {
		return known.local
	}
	taken := func(candidate string) bool {
		if g.source.pkg.Scope().Lookup(candidate) != nil || slices.Contains(locals, candidate) {
			return true
		}
		for _, known := range g.imports {
			if known.local == candidate {
				return true
			}
		}
		return false
	}
	local := name
	for suffix := 2; taken(local); suffix++ {
		local = name + strconv.Itoa(suffix)
	}
	g.imports[path] = imported{local: local}
	if local != name {
		g.imports[path] = imported{local: local, alias: local}
	}
	return local
}

// locals are the parameter names of generated functions in whose bodies the
// author's types are spelled.
var locals = []string{"ctx", "request", "method", "input", "e", "c"}

// local returns a parameter name that does not hide a declaration of the
// package, such as a type named request.
func (g *generator) local(name string) string {
	for g.source.pkg.Scope().Lookup(name) != nil {
		name += "_"
	}
	return name
}

func (g *generator) std(path string) string {
	return g.use(path, path[strings.LastIndex(path, "/")+1:])
}

func (g *generator) kernel() string   { return g.use(kernelPath, "cordis") }
func (g *generator) contract() string { return g.use(kernelPath+"/contract", "contract") }
func (g *generator) schema() string   { return g.use(kernelPath+"/schema", "schema") }

// typeName spells a type as the generated file must write it.
func (g *generator) typeName(t types.Type) string {
	if t == nil {
		return "struct{}"
	}
	return types.TypeString(t, func(pkg *types.Package) string {
		if pkg == g.source.pkg {
			return ""
		}
		return g.use(pkg.Path(), pkg.Name())
	})
}

// declare reserves a generated package-level name.
func (g *generator) declare(name string) string {
	if existing := g.source.pkg.Scope().Lookup(name); existing != nil && g.err == nil {
		g.err = g.source.errorf(existing.Pos(), "%s is declared here and is also a generated name", name)
	}
	if g.names[name] && g.err == nil {
		g.err = fmt.Errorf("generated name %s is needed twice", name)
	}
	g.names[name] = true
	return name
}

// qualify spells a generated name of the package that declares a service.
func (g *generator) qualify(s *service, name string) string {
	if s.local {
		return name
	}
	return g.use(s.object.Pkg().Path(), s.object.Pkg().Name()) + "." + name
}

func (g *generator) service(s *service, declared schema.Service) {
	name := s.object.Name()
	key := contract.Service{Name: s.name, Major: s.major}.Key()
	context := g.std("context") + ".Context"
	raw := g.std("encoding/json") + ".RawMessage"
	ctx, method, input, e := g.local("ctx"), g.local("method"), g.local("input"), g.local("e")
	endpointType, clientType := g.declare("generatedEndpoint_"+name), g.declare("generatedClient_"+name)

	g.line("// %s identifies service %s and the minor this code was generated from.", g.declare(name+"Service"), s.name)
	g.line("func %sService() %s.Service { return %s.Service{Name: %q, Major: %d, Minor: %d} }", name, g.contract(), g.contract(), s.name, s.major, s.minor)
	g.line("// %s is what a package that needs the service declares to the host.", g.declare(name+"Consumer"))
	g.line("func %sConsumer(minMinor, maxMinor uint32) %s.Consumer { return %s.Consumer{Requirement: %s.Requirement{Name: %q, Major: %d, MinMinor: minMinor, MaxMinor: maxMinor}, Contract: %q} }",
		name, g.contract(), g.contract(), g.contract(), s.name, s.major, declared.Consumer(0, 0).Contract)
	g.line("// %s is the key the service is provided and required under.", g.declare(name+"Endpoint"))
	g.line("var %sEndpoint = %s.EndpointKey(%q, %d)", name, g.contract(), s.name, s.major)
	g.line("// %s requires the service with a minor in [minMinor, maxMinor].", g.declare(name+"Requirement"))
	g.line("func %sRequirement(minMinor, maxMinor uint32) %s.Requirement { return %s.Require(%sEndpoint, minMinor, maxMinor) }", name, g.kernel(), g.contract(), name)
	g.line("// %s provides implementation on s for as long as s lives.", g.declare("Provide"+name))
	g.line("func Provide%s(s *%s.Scope, implementation %s) error { return %sEndpoint.Provide(s, New%sEndpoint(implementation)) }", name, g.kernel(), name, name, name)
	g.line("// %s returns a client for the service visible from s.", g.declare("Get"+name))
	g.line("func Get%s(s *%s.Scope) (%s, error) { endpoint, err := %sEndpoint.Get(s); if err != nil { return nil, err }; return New%sClient(endpoint) }", name, g.kernel(), name, name, name)

	operations := map[string]string{}
	wires := map[string]schema.Method{}
	for _, m := range declared.Methods {
		wires[m.Name] = m
	}
	for _, m := range s.methods {
		operation := g.declare("generatedOperation_" + name + "_" + m.name)
		operations[m.name] = operation
		g.line("var %s = %s.NewOperation[%s, %s](%q, %s, %s)", operation, g.schema(), g.typeName(m.request), g.typeName(m.response), m.wire,
			strconv.Quote(string(wires[m.wire].Request)), strconv.Quote(string(wires[m.wire].Response)))
	}

	g.line("type %s struct{ implementation %s }", endpointType, name)
	g.line("// %s adapts an implementation to the endpoint clients call, in this process or", g.declare("New"+name+"Endpoint"))
	g.line("// from another one.")
	g.line("func New%sEndpoint(implementation %s) %s.Endpoint { return &%s{implementation: implementation} }", name, name, g.contract(), endpointType)
	g.line("func (%s *%s) Service() %s.Service { return %sService() }", e, endpointType, g.contract(), name)
	g.line("func (%s *%s) Call(%s %s, %s string, %s %s) (%s, error) {\nswitch %s {", e, endpointType, ctx, context, method, input, raw, raw, method)
	for _, m := range s.methods {
		if !m.stream {
			g.line("case %q:\nreturn %s.Serve(%s, %s, %s)", m.wire, operations[m.name], ctx, input, g.adapt(e+".implementation", m))
		}
	}
	g.line("}\nreturn nil, %s.Fail(%s.Invalid, %q + %s + %q)\n}", g.contract(), g.contract(), "service "+key+" has no method \"", method, "\"")
	g.line("func (%s *%s) Stream(%s %s, %s string, %s %s) %s.Seq2[%s, error] {\nswitch %s {", e, endpointType, ctx, context, method, input, raw, g.std("iter"), raw, method)
	for _, m := range s.methods {
		if m.stream {
			g.line("case %q:\nreturn %s.ServeStream(%s, %s, %s)", m.wire, operations[m.name], ctx, input, g.adapt(e+".implementation", m))
		}
	}
	g.line("}\nreturn %s.FailedStream(%s.Fail(%s.Invalid, %q + %s + %q))\n}", g.contract(), g.contract(), g.contract(), "service "+key+" has no streaming method \"", method, "\"")

	g.line("type %s struct { endpoint %s.Endpoint }", clientType, g.contract())
	g.line("// %s returns a typed client for endpoint. Requests and responses are", g.declare("New"+name+"Client"))
	g.line("// validated and cross as JSON, in this process as between processes.")
	g.line("func New%sClient(endpoint %s.Endpoint) (%s, error) {", name, g.contract(), name)
	g.line("if endpoint == nil { return nil, %s.Fail(%s.Invalid, %q) }", g.contract(), g.contract(), "client for "+key+" needs an endpoint")
	g.line("if provided := endpoint.Service(); provided.Name != %q || provided.Major != %d { return nil, %s.Fail(%s.Incompatible, \"endpoint provides \" + provided.Key() + %q) }",
		s.name, s.major, g.contract(), g.contract(), ", client is for "+key)
	g.line("return &%s{endpoint: endpoint}, nil\n}", clientType)
	for _, m := range s.methods {
		g.client(clientType, operations[m.name], m)
	}
}

// adapt returns a function with the shape an operation calls, around a
// method that may take no request or return no response.
func (g *generator) adapt(target string, m method) string {
	if m.request != nil && (m.response != nil || m.stream) {
		return target + "." + m.name
	}
	context := g.std("context") + ".Context"
	ctx, request := g.local("ctx"), g.local("request")
	parameter, argument := "_ struct{}", ""
	if m.request != nil {
		parameter, argument = request+" "+g.typeName(m.request), ", "+request
	}
	call := fmt.Sprintf("%s.%s(%s%s)", target, m.name, ctx, argument)
	switch {
	case m.stream:
		return fmt.Sprintf("func(%s %s, %s) %s.Seq2[%s, error] { return %s }", ctx, context, parameter, g.std("iter"), g.typeName(m.response), call)
	case m.response != nil:
		return fmt.Sprintf("func(%s %s, %s) (%s, error) { return %s }", ctx, context, parameter, g.typeName(m.response), call)
	}
	return fmt.Sprintf("func(%s %s, %s) (struct{}, error) { return struct{}{}, %s }", ctx, context, parameter, call)
}

func (g *generator) client(receiver, operation string, m method) {
	context := g.std("context") + ".Context"
	ctx, request, c := g.local("ctx"), g.local("request"), g.local("c")
	parameter, input := "", "struct{}{}"
	if m.request != nil {
		parameter, input = ", "+request+" "+g.typeName(m.request), request
	}
	call := fmt.Sprintf("(%s, %s.endpoint, %s)", ctx, c, input)
	switch {
	case m.stream:
		g.line("func (%s *%s) %s(%s %s%s) %s.Seq2[%s, error] { return %s.CallStream%s }", c, receiver, m.name, ctx, context, parameter, g.std("iter"), g.typeName(m.response), operation, call)
	case m.response != nil:
		g.line("func (%s *%s) %s(%s %s%s) (%s, error) { return %s.Call%s }", c, receiver, m.name, ctx, context, parameter, g.typeName(m.response), operation, call)
	default:
		g.line("func (%s *%s) %s(%s %s%s) error { _, err := %s.Call%s; return err }", c, receiver, m.name, ctx, context, parameter, operation, call)
	}
}

func (g *generator) plugin(p *plugin, declared schema.PluginDefinition, spec contract.DefinitionSpec, services map[string]*service) {
	name := exported(p.id)
	codec := g.declare("generatedConfig_" + name)
	config := g.typeName(p.config)
	g.line("var %s = %s.NewCodec[%s](%s)", codec, g.schema(), config, strconv.Quote(string(declared.Config)))
	var requirements, consumers, provided []string
	for _, r := range declared.Requires {
		s := services[r.Service]
		requirements = append(requirements, fmt.Sprintf("%s(%d, %d)", g.qualify(s, s.object.Name()+"Requirement"), r.MinMinor, r.MaxMinor))
		consumers = append(consumers, fmt.Sprintf("%s(%d, %d)", g.qualify(s, s.object.Name()+"Consumer"), r.MinMinor, r.MaxMinor))
	}
	for _, service := range spec.Provides {
		s := services[service.Name]
		provided = append(provided, g.qualify(s, s.object.Name()+"Service")+"()")
	}
	g.line("// %s is plugin %q. It runs in process as it is, or as a native package", g.declare(name+"Plugin"), p.id)
	g.line("// through sdk.Define.")
	g.line("var %sPlugin = %s.Plugin[%s]{Name: %q, Requires: []%s.Requirement{%s}, Validate: %s.Check, Start: %s}",
		name, g.kernel(), config, p.id, g.kernel(), strings.Join(requirements, ", "), codec, p.function.Name())
	g.line("// %s describes the plugin to a host.", g.declare(name+"DefinitionSpec"))
	g.line("func %sDefinitionSpec() %s.DefinitionSpec { return %s.DefinitionSpec{ID: %q, ConfigSchema: %s.Schema(), Requires: []%s.Consumer{%s}, Provides: []%s.Service{%s}} }",
		name, g.contract(), g.contract(), p.id, codec, g.contract(), strings.Join(consumers, ", "), g.contract(), strings.Join(provided, ", "))
}

// exported turns a plugin id such as "http-server" into HttpServer.
func exported(id string) string {
	var name strings.Builder
	upper := true
	for _, r := range id {
		switch {
		case r == '-' || r == '_' || r == '.' || r == '/' || r == ':':
			upper = true
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			return ""
		case upper:
			name.WriteRune(unicode.ToUpper(r))
			upper = false
		default:
			name.WriteRune(r)
		}
	}
	return name.String()
}

// Generate emits a complete Go file containing request/response data types,
// validating JSON codecs, typed clients and typed server registration functions.
// The caller owns file creation. Invalid declarations produce no partial output.
func Generate(w io.Writer, packageName string, definition Definition) error {
	return generate(w, packageName, definition)
}

// GenerateMany checks a whole output package and formats it before writing once.
func GenerateMany(w io.Writer, packageName string, definitions ...Definition) error {
	return generate(w, packageName, definitions...)
}

func generate(w io.Writer, packageName string, definitions ...Definition) error {
	if w == nil {
		return fmt.Errorf("generate contract: nil writer")
	}
	if !token.IsIdentifier(packageName) || packageName == "_" {
		return fmt.Errorf("generate contract: invalid Go package name")
	}
	if len(definitions) == 0 {
		return fmt.Errorf("generate contract: no declarations")
	}
	normalized := make([]Definition, 0, len(definitions))
	for _, d := range definitions {
		n, err := d.normalized()
		if err != nil {
			return err
		}
		normalized = append(normalized, n)
	}
	sort.Slice(normalized, func(i, j int) bool {
		a, _ := json.Marshal(normalized[i])
		b, _ := json.Marshal(normalized[j])
		return bytes.Compare(a, b) < 0
	})
	g := &generator{names: map[string]string{
		"context": "shared import", "json": "shared import", "fmt": "shared import",
		"contract": "shared import", "schema": "shared import",
	}}
	g.line("// Code generated by cordis/schema. DO NOT EDIT.\npackage %s\n", packageName)
	g.line("import (\n\"context\"\n\"encoding/json\"\n\"fmt\"\n\"github.com/Cyenoch/cordis/contract\"\n\"github.com/Cyenoch/cordis/schema\"\n)\n")
	// Imports remain used even for a document containing only a scalar named type.
	g.line("var _ context.Context; var _ contract.Scope")
	for i, d := range normalized {
		g.origin = fmt.Sprintf("input %d", i+1)
		for _, s := range d.Services {
			g.origin = fmt.Sprintf("input %d service %s", i+1, s.Name)
			name, _ := exportedName(s.Name)
			for _, symbol := range []string{name + "Client", name + "Server", name + "Service", name + "Consumer", "New" + name + "Client", "Register" + name + "Server"} {
				g.reserve(symbol)
			}
		}
		for _, pd := range d.Definitions {
			g.origin = fmt.Sprintf("input %d definition %s", i+1, pd.ID)
			name, _ := exportedName(pd.ID)
			g.reserve(name + "DefinitionSpec")
			g.reserve("New" + name + "Definition")
			for _, c := range pd.Requires {
				cn, _ := exportedName(c.Name)
				g.reserve(name + cn + "Consumer")
			}
		}
	}
	for i, d := range normalized {
		declarationHash, _ := d.Fingerprint()
		for _, name := range sortedKeys(d.Types) {
			g.origin = fmt.Sprintf("input %d type %s", i+1, name)
			gn, _ := exportedName(name)
			compiled, _ := Compile(d.Types[name])
			g.emitType(gn, compiled.root)
		}
		specs := d.specs()
		for i, pd := range d.Definitions {
			g.origin = "definition " + pd.ID
			name, _ := exportedName(pd.ID)
			g.reserve(name + "DefinitionDeclarationFingerprint")
			g.line("const %sDefinitionDeclarationFingerprint = %q", name, declarationHash)
			compiled, _ := Compile(pd.Config)
			g.emitType(name+"Config", compiled.root)
			g.emitDefinition(name, pd, specs[i])
		}
		for _, service := range d.Services {
			g.origin = "service " + service.Name
			name, _ := exportedName(service.Name)
			g.reserve(name + "ServiceDeclarationFingerprint")
			g.line("const %sServiceDeclarationFingerprint = %q", name, declarationHash)
			for _, method := range service.Methods {
				mn, _ := exportedName(method.Name)
				for _, part := range []struct {
					suffix string
					raw    json.RawMessage
				}{{"Request", method.Request}, {"Response", method.Response}} {
					compiled, _ := Compile(part.raw)
					g.emitType(name+mn+part.suffix, compiled.root)
				}
			}
			g.emitService(name, service)
		}
	}
	if g.err != nil {
		return fmt.Errorf("generate contract: %w", g.err)
	}
	formatted, err := format.Source(g.buffer.Bytes())
	if err != nil {
		return fmt.Errorf("format generated contract: %w", err)
	}
	written, err := w.Write(formatted)
	if err != nil {
		return fmt.Errorf("write generated contract: %w", err)
	}
	if written != len(formatted) {
		return fmt.Errorf("write generated contract: %w", io.ErrShortWrite)
	}
	return nil
}

type generator struct {
	buffer bytes.Buffer
	names  map[string]string
	origin string
	err    error
}

func (g *generator) line(format string, args ...any) {
	if g.err != nil {
		return
	}
	if _, err := fmt.Fprintf(&g.buffer, format+"\n", args...); err != nil {
		g.err = err
	}
}

func (g *generator) reserve(name string) {
	if previous, exists := g.names[name]; exists {
		if g.err == nil {
			g.err = fmt.Errorf("generated identifier collision: %s (%s and %s)", name, previous, g.origin)
		}
		return
	}
	g.names[name] = g.origin
}

func (g *generator) emitType(name string, n *node) {
	g.reserve(name)
	g.reserve(name + "SchemaJSON")
	g.line("const %sSchemaJSON = %s", name, strconv.Quote(string(n.raw)))
	g.reserve("validate" + name)
	g.reserve("compiled" + name)
	g.reserve("compiled" + name + "Error")
	g.line("var compiled%s, compiled%sError = schema.Compile(json.RawMessage(%sSchemaJSON))", name, name, name)
	g.line("func validate%s(data []byte) error { if compiled%sError != nil { return compiled%sError }; return compiled%s.Validate(data) }", name, name, name, name)
	if n.nullable {
		plain, err := nonNullableNode(n)
		if err != nil {
			g.err = err
			return
		}
		g.emitType(name+"Value", plain)
		g.line("type %s struct { schema.Nullable[%sValue] }", name, name)
		g.line("func (v %s) MarshalJSON() ([]byte,error) { data,err := v.Nullable.MarshalJSON(); if err != nil { return nil,err }; if err := validate%s(data); err != nil { return nil,err }; return data,nil }", name, name)
		g.line("func (v *%s) UnmarshalJSON(data []byte) error { if v == nil { return fmt.Errorf(\"decode %s: nil receiver\") }; if err := validate%s(data); err != nil { return err }; var value schema.Nullable[%sValue]; if err := json.Unmarshal(data,&value); err != nil { return err }; v.Nullable = value; return nil }", name, name, name, name)
		return
	}
	switch n.kind {
	case "object":
		g.emitObject(name, n)
	case "union":
		g.emitUnion(name, n)
	default:
		underlying := ""
		switch n.kind {
		case "array":
			underlying = "[]" + g.fieldType(name+"Item", n.items)
		case "string":
			underlying = "string"
			switch n.format {
			case "int64":
				underlying = "schema.Int64"
			case "uint64":
				underlying = "schema.Uint64"
			case "byte":
				underlying = "[]byte"
			}
		case "number":
			underlying = "json.Number"
		case "integer":
			underlying = "int64"
		case "boolean":
			underlying = "bool"
		}
		g.line("type %s %s", name, underlying)
		encoder := "contract.Encode"
		if n.kind == "integer" {
			encoder = "json.Marshal"
		}
		g.line("func (v %s) MarshalJSON() ([]byte,error) { data,err := %s((%s)(v)); if err != nil { return nil,err }; if err := validate%s(data); err != nil { return nil,err }; return data,nil }", name, encoder, underlying, name)
		if n.kind == "integer" {
			g.line("func (v *%s) UnmarshalJSON(data []byte) error { if v == nil { return fmt.Errorf(\"decode %s: nil receiver\") }; if err := validate%s(data); err != nil { return err }; var value float64; if err := json.Unmarshal(data,&value); err != nil { return err }; *v = %s(int64(value)); return nil }", name, name, name, name)
		} else {
			g.line("func (v *%s) UnmarshalJSON(data []byte) error { if v == nil { return fmt.Errorf(\"decode %s: nil receiver\") }; if err := validate%s(data); err != nil { return err }; var value %s; if err := json.Unmarshal(data,&value); err != nil { return err }; *v = %s(value); return nil }", name, name, name, underlying, name)
		}
	}
}

func (g *generator) emitObject(name string, n *node) {
	fields := make(map[string]string, len(n.properties))
	types := make(map[string]string, len(n.properties))
	used := map[string]bool{"MarshalJSON": true, "UnmarshalJSON": true}
	for _, key := range sortedKeys(n.properties) {
		fieldName, err := exportedName(key)
		if err != nil {
			g.err = fmt.Errorf("property %s: %w", key, err)
			return
		}
		if used[fieldName] {
			g.err = fmt.Errorf("property name collision in %s: %s", name, key)
			return
		}
		used[fieldName] = true
		fields[key] = fieldName
		types[key] = g.fieldType(name+fieldName, n.properties[key])

	}
	g.line("type %s struct {", name)
	for _, key := range sortedKeys(n.properties) {
		typ := types[key]
		if !n.required[key] {
			typ = "schema.Optional[" + typ + "]"
		}
		g.line("%s %s `json:%s`", fields[key], typ, strconv.Quote(key))
	}
	g.line("}")
	g.line("func (v %s) MarshalJSON() ([]byte,error) {", name)
	g.line("object := make(map[string]json.RawMessage,%d)", len(n.properties))
	for _, key := range sortedKeys(n.properties) {
		access := "v." + fields[key]
		if !n.required[key] {
			g.line("if %s.Present {", access)
			access += ".Value"
		}
		g.line("{ data,err := contract.Encode(%s); if err != nil { return nil,fmt.Errorf(%s,err) }; object[%s] = data }", access, strconv.Quote("encode field "+key+": %w"), strconv.Quote(key))
		if !n.required[key] {
			g.line("}")
		}
	}
	g.line("data,err := json.Marshal(object); if err != nil { return nil,err }; if err := validate%s(data); err != nil { return nil,err }; return data,nil\n}", name)
	g.line("func (v *%s) UnmarshalJSON(data []byte) error {", name)
	g.line("if v == nil { return fmt.Errorf(\"decode %s: nil receiver\") }; if err := validate%s(data); err != nil { return err }", name, name)
	g.line("var object map[string]json.RawMessage; if err := json.Unmarshal(data,&object); err != nil { return err }; var value %s", name)
	for _, key := range sortedKeys(n.properties) {
		access := "value." + fields[key]
		if !n.required[key] {
			g.line("if raw,exists := object[%s]; exists {", strconv.Quote(key))
			g.line("%s.Present = true", access)
			access += ".Value"
		} else {
			g.line("{ raw := object[%s]", strconv.Quote(key))
		}
		g.line("if err := json.Unmarshal(raw,&%s); err != nil { return fmt.Errorf(%s,err) }\n}", access, strconv.Quote("decode field "+key+": %w"))
	}
	g.line("*v = value; return nil\n}")
}

func (g *generator) emitUnion(name string, n *node) {
	fields := map[string]string{}
	used := map[string]bool{}
	for _, tag := range sortedKeys(n.variants) {
		fieldName, err := exportedName("variant-" + tag)
		if err != nil {
			g.err = fmt.Errorf("union tag %s: %w", tag, err)
			return
		}
		if used[fieldName] {
			g.err = fmt.Errorf("union tag identifier collision: %s", tag)
			return
		}
		used[fieldName] = true
		fields[tag] = fieldName
		g.emitType(name+fieldName, n.variants[tag])
	}
	g.line("// %s contains exactly one present variant; the variant's const field is the wire tag.", name)
	g.line("type %s struct {", name)
	for _, tag := range sortedKeys(n.variants) {
		g.line("%s schema.Optional[%s%s] `json:\"-\"`", fields[tag], name, fields[tag])
	}
	g.line("}")
	for _, tag := range sortedKeys(n.variants) {
		constructor := "New" + name + fields[tag]
		g.reserve(constructor)
		tagField, _ := exportedName(n.discriminator)
		tagValue := strconv.Quote(tag)
		switch n.variants[tag].properties[n.discriminator].format {
		case "int64":
			tagValue = "schema.Int64(" + tag + ")"
		case "uint64":
			tagValue = "schema.Uint64(" + tag + ")"
		case "byte":
			decoded, _ := base64.StdEncoding.DecodeString(tag)
			tagValue = "[]byte(" + strconv.Quote(string(decoded)) + ")"
		}
		g.line("func %s(value %s%s) %s { value.%s = %s; return %s{%s:schema.Some(value)} }", constructor, name, fields[tag], name, tagField, tagValue, name, fields[tag])
	}
	g.line("func (v %s) MarshalJSON() ([]byte,error) { var data []byte; var err error; count := 0", name)
	for _, tag := range sortedKeys(n.variants) {
		g.line("if v.%s.Present { count++; data,err = json.Marshal(v.%s.Value); if err != nil { return nil,err } }", fields[tag], fields[tag])
	}
	g.line("if count != 1 { return nil,fmt.Errorf(\"union %s requires exactly one variant\") }; if err := validate%s(data); err != nil { return nil,err }; return data,nil\n}", name, name)
	g.line("func (v *%s) UnmarshalJSON(data []byte) error { if v == nil { return fmt.Errorf(\"decode %s: nil receiver\") }; if err := validate%s(data); err != nil { return err }; var object map[string]json.RawMessage; if err := json.Unmarshal(data,&object); err != nil { return err }; var tag string; if err := json.Unmarshal(object[%s],&tag); err != nil { return err }; var value %s; switch tag {", name, name, name, strconv.Quote(n.discriminator), name)
	for _, tag := range sortedKeys(n.variants) {
		g.line("case %s: value.%s.Present = true; if err := json.Unmarshal(data,&value.%s.Value); err != nil { return err }", strconv.Quote(tag), fields[tag], fields[tag])
	}
	g.line("default: return fmt.Errorf(\"unknown union tag\") }; *v = value; return nil\n}")
}

func (g *generator) emitService(name string, s Service) {
	g.line("func %sService() contract.Service { return contract.Service{Name:%q,Major:%d,Minor:%d} }", name, s.Name, s.Major, s.Minor)
	g.line("func %sConsumer(minMinor,maxMinor uint32) contract.Consumer { return contract.Consumer{Requirement:contract.Requirement{Name:%q,Major:%d,MinMinor:minMinor,MaxMinor:maxMinor},Contract:%q} }", name, s.Name, s.Major, s.methodFingerprint())
	g.line("type %sClient struct { caller contract.Caller; consumer contract.Consumer }", name)
	g.line("func New%sClient(caller contract.Caller,consumer contract.Consumer) (*%sClient,error) { if caller==nil { return nil,fmt.Errorf(\"service client requires caller\") }; if err:=consumer.Check(%q,%d,%d,%q);err!=nil{return nil,err};return &%sClient{caller:caller,consumer:consumer},nil }", name, name, s.Name, s.Major, s.Minor, s.methodFingerprint(), name)
	g.line("type %sServer interface {", name)
	for _, method := range s.Methods {
		mn, err := exportedName(method.Name)
		if err != nil {
			g.err = err
			return
		}
		g.line("%s(context.Context,%s%sRequest) (%s%sResponse,error)", mn, name, mn, name, mn)
	}
	g.line("}")
	for _, method := range s.Methods {
		mn, err := exportedName(method.Name)
		if err != nil {
			g.err = err
			return
		}
		g.line("func (c *%sClient) %s(ctx context.Context,input %s%sRequest) (%s%sResponse,error) {", name, mn, name, mn, name, mn)
		g.line("var output %s%sResponse; if c == nil || c.caller == nil { return output,fmt.Errorf(\"service client has no caller\") }; data,err := json.Marshal(input); if err != nil { return output,err }", name, mn)
		g.line("request,err := json.Marshal(struct { Method string `json:\"method\"`; Input json.RawMessage `json:\"input\"` }{Method:%s,Input:data}); if err != nil { return output,err }", strconv.Quote(method.Name))
		g.line("response,err := c.caller.Call(ctx,c.consumer.Requirement,request); if err != nil { return output,err }; if err := json.Unmarshal(response,&output); err != nil { return output,err }; return output,nil\n}")
	}
	g.line("func Register%sServer(registrar contract.Registrar,implementation %sServer) error {", name, name)
	g.line("if registrar == nil || implementation == nil { return fmt.Errorf(\"service registration requires registrar and implementation\") }")
	g.line("return registrar.Provide(%sService(),func(ctx context.Context,data json.RawMessage) (json.RawMessage,error) {", name)
	g.line("var envelope struct { Method string `json:\"method\"`; Input json.RawMessage `json:\"input\"` }; if err := contract.Decode(data,&envelope); err != nil { return nil,err }; if envelope.Method == \"\" || len(envelope.Input) == 0 { return nil,contract.Fail(contract.Invalid,\"service envelope requires method and input\") }; switch envelope.Method {")
	for _, method := range s.Methods {
		mn, err := exportedName(method.Name)
		if err != nil {
			g.err = err
			return
		}
		g.line("case %s: var input %s%sRequest; if err := json.Unmarshal(envelope.Input,&input); err != nil { return nil,err }; output,err := implementation.%s(ctx,input); if err != nil { return nil,err }; response,err := json.Marshal(output); if err != nil { return nil,err }; return response,nil", strconv.Quote(method.Name), name, mn, mn)
	}
	g.line("default: return nil,contract.Fail(contract.Invalid,\"unknown service method\") }\n})\n}")
}

func (g *generator) fieldType(name string, n *node) string {
	if n.nullable {
		plain, err := nonNullableNode(n)
		if err != nil {
			g.err = err
			return ""
		}
		return "schema.Nullable[" + g.fieldType(name+"Value", plain) + "]"
	}
	switch n.kind {
	case "string":
		switch n.format {
		case "int64":
			return "schema.Int64"
		case "uint64":
			return "schema.Uint64"
		case "byte":
			return "[]byte"
		}
		return "string"
	case "boolean":
		return "bool"
	case "integer", "number":
		return "json.Number"
	case "array":
		return "[]" + g.fieldType(name+"Item", n.items)
	default:
		g.emitType(name, n)
		return name
	}
}

func nonNullableNode(n *node) (*node, error) {
	plain := *n
	plain.nullable = false
	var object map[string]json.RawMessage
	if err := json.Unmarshal(n.raw, &object); err != nil {
		return nil, err
	}
	delete(object, "nullable")
	// Null alternatives belong to the outer wrapper, not its nonnull value.
	if len(n.enum) > 0 {
		plain.enum = []json.RawMessage{}
		for _, item := range n.enum {
			if !isNull(item) {
				plain.enum = append(plain.enum, item)
			}
		}
		if len(plain.enum) == 0 {
			delete(object, "enum")
		} else {
			object["enum"], _ = json.Marshal(plain.enum)
		}
	}
	if isNull(n.constant) {
		plain.constant = nil
		delete(object, "const")
	}
	raw, err := json.Marshal(object)
	plain.raw = raw
	return &plain, err
}

func (g *generator) emitDefinition(name string, pd PluginDefinition, spec contract.DefinitionSpec) {
	g.line("func %sDefinitionSpec() contract.DefinitionSpec { return contract.DefinitionSpec{ID:%q,ConfigSchema:json.RawMessage(%sConfigSchemaJSON),", name, spec.ID, name)
	g.line("Requires:[]contract.Consumer{")
	for _, consumer := range spec.Requires {
		r := consumer.Requirement
		g.line("{Requirement:contract.Requirement{Name:%q,Major:%d,MinMinor:%d,MaxMinor:%d},Contract:%q},", r.Name, r.Major, r.MinMinor, r.MaxMinor, consumer.Contract)
	}
	g.line("},Provides:[]contract.Service{")
	for _, service := range spec.Provides {
		g.line("{Name:%q,Major:%d,Minor:%d},", service.Name, service.Major, service.Minor)
	}
	g.line("}} }")
	for i, c := range pd.Requires {
		cn, _ := exportedName(c.Name)
		consumer := spec.Requires[i]
		r := consumer.Requirement
		g.line("func %s%sConsumer() contract.Consumer { return contract.Consumer{Requirement:contract.Requirement{Name:%q,Major:%d,MinMinor:%d,MaxMinor:%d},Contract:%q} }", name, cn, r.Name, r.Major, r.MinMinor, r.MaxMinor, consumer.Contract)
	}
	g.line("func New%sDefinition(start func(context.Context,contract.Scope,%sConfig)error) contract.Definition { spec:=%sDefinitionSpec();return contract.Definition{ID:spec.ID,Requires:spec.Requirements(),Provides:spec.Provides,Validate:func(raw json.RawMessage)error{var config %sConfig;return json.Unmarshal(raw,&config)},Start:func(ctx context.Context,scope contract.Scope)error{if start==nil{return fmt.Errorf(\"definition requires start\")};var config %sConfig;if err:=json.Unmarshal(scope.Config(),&config);err!=nil{return err};return start(ctx,scope,config)}} }", name, name, name, name, name)
}

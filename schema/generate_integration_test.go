package schema_test

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"testing"

	"github.com/Cyenoch/cordis/schema"
)

// This compiles and exercises a generated consumer module rather than comparing
// source strings. The module is external to the framework and uses public APIs.
func TestGeneratedExternalModule(t *testing.T) {
	data, err := os.ReadFile("testdata/echo.schema.json")
	if err != nil {
		t.Fatal(err)
	}
	definition, err := schema.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := schema.Generate(&generated, "echo", definition); err != nil {
		t.Fatal(err)
	}
	consumer, err := os.ReadFile("testdata/consumer_test.go.txt")
	if err != nil {
		t.Fatal(err)
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	module := "module generated-consumer\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => " + strconv.Quote(root) + "\n"
	for _, file := range []struct {
		name string
		data []byte
	}{{"go.mod", []byte(module)}, {"echo.go", generated.Bytes()}, {"echo_test.go", consumer}} {
		if err := os.WriteFile(filepath.Join(directory, file.name), file.data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	result, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("generated consumer failed: %v\n%s", err, result)
	}
}

func TestGeneratedNumbersPreserveTheirSchema(t *testing.T) {
	definition := schema.Definition{Schema: schema.DefinitionSchema, Services: []schema.Service{{Name: "number", Major: 1, Methods: []schema.Method{
		{Name: "exact", Request: []byte(`{"type":"number","const":0.10000000000000001}`), Response: []byte(`{"type":"number"}`)},
		{Name: "minimum", Request: []byte(`{"type":"number","minimum":0.10000000000000001}`), Response: []byte(`{"type":"number"}`)},
	}}}}
	var generated bytes.Buffer
	if err := schema.Generate(&generated, "numbers", definition); err != nil {
		t.Fatal(err)
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	consumer := `package numbers
import("encoding/json";"testing")
func TestRoundTrip(t *testing.T){
 for _,v:=range []any{new(NumberExactRequest),new(NumberMinimumRequest)}{
  raw:=[]byte("0.10000000000000001")
  if err:=json.Unmarshal(raw,v);err!=nil{t.Fatal(err)}
  out,err:=json.Marshal(v);if err!=nil||string(out)!=string(raw){t.Fatalf("out=%s err=%v",out,err)}
 }
}`
	for name, data := range map[string][]byte{"go.mod": []byte("module number-consumer\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => " + strconv.Quote(root) + "\n"), "numbers.go": generated.Bytes(), "numbers_test.go": []byte(consumer)} {
		if err := os.WriteFile(filepath.Join(directory, name), data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated number round trip: %v\n%s", err, output)
	}
}

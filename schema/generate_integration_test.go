// This compiles and exercises a generated consumer module rather than comparing
// source strings. The module is external to the framework and uses public APIs.
func TestGeneratedExternalModule(t *testing.T) {
	data, err := os.ReadFile("testdata/echo.schema.json")
	if err != nil {
		t.Fatal(err)
	}
	definition, err := schema.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := schema.Generate(&generated, "echo", definition); err != nil {
		t.Fatal(err)
	}
	consumer, err := os.ReadFile("testdata/consumer_test.go.txt")
	if err != nil {
		t.Fatal(err)
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	module := "module generated-consumer\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => " + strconv.Quote(root) + "\n"
	for _, file := range []struct {
		name string
		data []byte
	}{{"go.mod", []byte(module)}, {"echo.go", generated.Bytes()}, {"echo_test.go", consumer}} {
		if err := os.WriteFile(filepath.Join(directory, file.name), file.data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	result, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("generated consumer failed: %v\n%s", err, result)
	}
}

func TestGeneratedNumbersPreserveTheirSchema(t *testing.T) {
	definition := schema.Definition{Schema: schema.DefinitionSchema, Services: []schema.Service{{Name: "number", Major: 1, Methods: []schema.Method{
		{Name: "exact", Request: []byte(`{"type":"number","const":0.10000000000000001}`), Response: []byte(`{"type":"number"}`)},
		{Name: "minimum", Request: []byte(`{"type":"number","minimum":0.10000000000000001}`), Response: []byte(`{"type":"number"}`)},
	}}}}
	var generated bytes.Buffer
	if err := schema.Generate(&generated, "numbers", definition); err != nil {
		t.Fatal(err)
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	consumer := `package numbers
import("encoding/json";"testing")
func TestRoundTrip(t *testing.T){
 for _,v:=range []any{new(NumberExactRequest),new(NumberMinimumRequest)}{
  raw:=[]byte("0.10000000000000001")
  if err:=json.Unmarshal(raw,v);err!=nil{t.Fatal(err)}
  out,err:=json.Marshal(v);if err!=nil||string(out)!=string(raw){t.Fatalf("out=%s err=%v",out,err)}
 }
}`
	for name, data := range map[string][]byte{"go.mod": []byte("module number-consumer\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => " + strconv.Quote(root) + "\n"), "numbers.go": generated.Bytes(), "numbers_test.go": []byte(consumer)} {
		if err := os.WriteFile(filepath.Join(directory, name), data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated number round trip: %v\n%s", err, output)
	}
}

func TestGeneratedComposableDefinitions(t *testing.T) {
	source := `{"schema":"cordis-go.contract/v1","types":{"Label":{"type":"string","minLength":2},"CodeChoice":{"oneOf":[{"type":"object","properties":{"kind":{"type":"string","format":"int64","const":"1"}},"required":["kind"]},{"type":"object","properties":{"kind":{"type":"string","format":"uint64","const":"2"}},"required":["kind"]}],"discriminator":{"propertyName":"kind"}}},"services":[{"name":"alpha","version":"1.1","methods":[{"name":"echo","request":{"type":"object","properties":{"text":{"type":"string"}},"required":["text"]},"response":{"type":"object","properties":{"text":{"type":"string"}},"required":["text"]}}]}],"definitions":[{"id":"panel","config":{"type":"object","properties":{"title":{"type":"string","minLength":2},"note":{"type":"string","nullable":true},"details":{"type":"object","nullable":true,"properties":{"name":{"type":"string"}},"required":["name"]},"enabled":{"type":"boolean"}},"required":["title","note"]},"provides":["alpha"]},{"id":"counter","config":{"type":"integer","minimum":2},"requires":[{"name":"source","service":"alpha","minMinor":1,"maxMinor":3}]}]}`
	second := `{"schema":"cordis-go.contract/v1","services":[{"name":"beta","version":1,"methods":[{"name":"echo","request":{"type":"object","properties":{"text":{"type":"string"}},"required":["text"]},"response":{"type":"object","properties":{"text":{"type":"string"}},"required":["text"]}}]}],"definitions":[{"id":"contribution"}]}`
	a, err := schema.Parse([]byte(source))
	if err != nil {
		t.Fatal(err)
	}
	b, err := schema.Parse([]byte(second))
	if err != nil {
		t.Fatal(err)
	}
	for _, combined := range []bool{false, true} {
		t.Run(strconv.FormatBool(combined), func(t *testing.T) {
			var first, second bytes.Buffer
			files := map[string][]byte{}
			if combined {
				if err := schema.GenerateMany(&first, "composed", a, b); err != nil {
					t.Fatal(err)
				}
				files["api.go"] = first.Bytes()
			} else {
				if err := schema.Generate(&first, "composed", a); err != nil {
					t.Fatal(err)
				}
				if err := schema.Generate(&second, "composed", b); err != nil {
					t.Fatal(err)
				}
				files["alpha.go"] = first.Bytes()
				files["beta.go"] = second.Bytes()
			}
			consumer, err := os.ReadFile("testdata/composable_test.go.txt")
			if err != nil {
				t.Fatal(err)
			}
			specs, err := a.Specs()
			if err != nil {
				t.Fatal(err)
			}
			raw, err := json.Marshal(specs)
			if err != nil {
				t.Fatal(err)
			}
			hash, err := a.Fingerprint()
			if err != nil {
				t.Fatal(err)
			}
			files["composed_test.go"] = consumer
			files["specs.json"] = raw
			files["fingerprint.txt"] = []byte(hash)
			runGeneratedModule(t, files)
		})
	}
}

func runGeneratedModule(t *testing.T, files map[string][]byte) {
	t.Helper()
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	files["go.mod"] = []byte("module composed-consumer\n\ngo 1.27.3\n\nrequire github.com/Cyenoch/cordis v0.0.0\nreplace github.com/Cyenoch/cordis => " + strconv.Quote(root) + "\n")
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(directory, name), data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("composable external module: %v\n%s", err, output)
	}
}

func TestGeneratedNumbersRejectEmptySourceValues(t *testing.T) {
	d, err := schema.Parse([]byte(`{"schema":"cordis-go.contract/v1","types":{"scalar":{"type":"number"}},"definitions":[{"id":"numbers","config":{"type":"object","properties":{"n":{"type":"number"},"items":{"type":"array","items":{"type":"integer"}},"maybe":{"type":"number","nullable":true}},"required":["n","items","maybe"]}}]}`))
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := schema.GenerateMany(&generated, "numbers", d); err != nil {
		t.Fatal(err)
	}
	runGeneratedModule(t, map[string][]byte{"numbers.go": generated.Bytes(), "numbers_test.go": []byte(`package numbers
import("encoding/json";"testing";"github.com/Cyenoch/cordis/schema")
func TestNumbers(t *testing.T) {
 valid:=NumbersConfig{N:json.Number("0"),Items:[]json.Number{},Maybe:schema.NonNull(json.Number("0"))}
 if _,err:=json.Marshal(valid);err!=nil{t.Fatal(err)}
 cases:=[]any{Scalar(""),NumbersConfig{Items:valid.Items,Maybe:valid.Maybe},NumbersConfig{N:valid.N,Items:[]json.Number{""},Maybe:valid.Maybe},NumbersConfig{N:valid.N,Items:valid.Items,Maybe:schema.NonNull(json.Number(""))}}
 for _,value:=range cases{if raw,err:=json.Marshal(value);err==nil{t.Fatalf("empty number became zero: %s",raw)}}
}`)})
}

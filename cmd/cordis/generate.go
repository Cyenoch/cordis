package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"github.com/Cyenoch/cordis/config"
	"github.com/Cyenoch/cordis/schema"
)

func generateCommand(flags *flag.FlagSet, parse func() (bool, error), out io.Writer) error {
	name := flags.String("package", "pluginapi", "generated Go package")
	output := flags.String("output", "", "Go output path; - explicitly selects stdout")
	inputFormat := flags.String("format", "", "contract format: toml, yaml or json (default: extension)")
	if done, err := parse(); done {
		return err
	}
	if flags.NArg() == 0 || *output == "" {
		return &usageError{message: commandUsage["generate"]}
	}
	if err := checkFormat(*inputFormat); err != nil {
		return err
	}
	definitions := make([]schema.Definition, 0, flags.NArg())
	for _, path := range flags.Args() {
		doc, err := config.Load(path, config.Format(*inputFormat))
		if err != nil {
			return err
		}
		definition, err := schema.Parse(doc.JSON)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		definitions = append(definitions, definition)
	}
	var generated bytes.Buffer
	if err := schema.GenerateMany(&generated, *name, definitions...); err != nil {
		return fmt.Errorf("generate %v: %w", flags.Args(), err)
	}
	if *output == "-" {
		_, err := generated.WriteTo(out)
		return err
	}
	return atomicOutput(*output, generated.Bytes())
}

func atomicOutput(path string, data []byte) (result error) {
	mode := os.FileMode(0644)
	if info, err := os.Lstat(path); err == nil {
		if !info.Mode().IsRegular() {
			return fmt.Errorf("output %q is not a regular file", path)
		}
		mode = info.Mode().Perm()
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect output %q: %w", path, err)
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".cordis-generate-*.go")
	if err != nil {
		return fmt.Errorf("create output for %q: %w", path, err)
	}
	temporary := file.Name()
	defer func() {
		if err := os.Remove(temporary); err != nil && !errors.Is(err, os.ErrNotExist) {
			result = errors.Join(result, fmt.Errorf("remove temporary output: %w", err))
		}
	}()
	_, writeErr := file.Write(data)
	if writeErr == nil {
		writeErr = file.Chmod(mode)
	}
	if writeErr == nil {
		writeErr = file.Sync()
	}
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return fmt.Errorf("write output %q: %w", path, err)
	}
	if err := renameOutput(temporary, path); err != nil {
		return fmt.Errorf("replace output %q: %w", path, err)
	}
	return nil
}

func checkFormat(value string) error {
	switch config.Format(value) {
	case "", config.TOML, config.YAML, config.JSON:
		return nil
	default:
		return &usageError{message: "format must be toml, yaml or json"}
	}
}

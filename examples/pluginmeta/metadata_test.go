package pluginmeta

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/Cyenoch/cordis/contract"
	"github.com/Cyenoch/cordis/packagehost"
)

func TestGeneratedDeclarationsMatchAuthor(t *testing.T) {
	for _, tc := range []struct {
		name     string
		manifest contract.Manifest
	}{{"counter", Counter()}, {"chain", Chain()}, {"resource", Resource()}, {"provider", Provider()}, {"consumer", Consumer()}} {
		t.Run(tc.name, func(t *testing.T) {
			dir := filepath.Join("..", "plugins", tc.name)
			author, err := packagehost.LoadAuthor(dir)
			if err != nil {
				t.Fatal(err)
			}
			want, err := json.Marshal(author.Manifest)
			if err != nil {
				t.Fatal(err)
			}
			got, err := json.Marshal(tc.manifest)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(got, want) {
				t.Fatal("host metadata is stale; run go generate ./examples/pluginmeta")
			}
			var generated bytes.Buffer
			if err := author.Generate(&generated, "main"); err != nil {
				t.Fatal(err)
			}
			got, err = os.ReadFile(filepath.Join(dir, "cordis_gen.go"))
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(got, generated.Bytes()) {
				t.Fatal("plugin code is stale; run go generate ./examples/pluginmeta")
			}
		})
	}
}

//go:build ignore

package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/Cyenoch/cordis/packagehost"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	var metadata bytes.Buffer
	fmt.Fprintln(&metadata, "// Code generated by go generate ./examples/pluginmeta. DO NOT EDIT.")
	fmt.Fprintln(&metadata, "package pluginmeta\nimport (\"encoding/json\"; \"github.com/Cyenoch/cordis/contract\")")
	for _, name := range []string{"counter", "chain", "resource", "provider", "consumer"} {
		dir := filepath.Join("..", "plugins", name)
		author, err := packagehost.LoadAuthor(dir)
		if err != nil {
			return err
		}
		var generated bytes.Buffer
		if err := author.Generate(&generated, "main"); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "cordis_gen.go"), generated.Bytes(), 0644); err != nil {
			return err
		}
		raw, err := json.Marshal(author.Manifest)
		if err != nil {
			return err
		}
		fmt.Fprintf(&metadata, "func %s() contract.Manifest { var manifest contract.Manifest; if err := json.Unmarshal([]byte(%q), &manifest); err != nil { panic(err) }; return manifest }\n", strings.ToUpper(name[:1])+name[1:], raw)
	}
	output, err := format.Source(metadata.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("manifests_gen.go", output, 0644)
}
